// Every fixed spoken line, for the audio generator.
export function allDialogue() {
  const out = [];
  const push = (arr, v) => (arr || []).forEach(l => out.push({ ja: l.ja, voice: l.voice || v || 'f' }));
  for (const m of Object.values(MAPS)) {
    for (const n of m.npcs || []) { push(n.talk, n.voice); push(n.after, n.voice); push(n.give, n.voice); push(n.win, n.voice); }
    for (const s of m.signs || []) if (s.ja) out.push({ ja: s.ja, voice: 'f' });
    out.push({ ja: m.name.ja, voice: 'f' });
  }
  for (const ms of Object.values(MASTERS)) { push(ms.pre, ms.voice); push(ms.win, ms.voice); push(ms.lose, ms.voice); push(ms.after, ms.voice); }
  for (const k of ['rival1', 'rival2', 'rival3']) { push(RIVAL[k].pre, 'k'); push(RIVAL[k].win, 'k'); push(RIVAL[k].lose, 'k'); }
  for (const arr of Object.values(STORY)) push(arr);
  return out;
}


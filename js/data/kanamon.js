// Rough power so evolved / rare creatures feel stronger.
export function power(id) {
  const m = MON[id];
  let stage = 0, x = m;
  while (x.from) { stage++; x = MON[x.from]; }
  return 1 + stage * 0.12 + (m.rare - 1) * 0.06;
}
